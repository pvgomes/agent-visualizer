export type ToolbarIcon = keyof typeof TOOLBAR;
export type Glyph = keyof typeof GLYPH;

export const icon = (name: ToolbarIcon, scale = 2): SVGSVGElement => pixels(TOOLBAR[name], scale, "icon");
export const glyph = (name: Glyph, scale = 2): SVGSVGElement => pixels(GLYPH[name], scale, "glyph");
export const mark = (scale = 2): SVGSVGElement => pixels(MARK, scale, "mark");

const BY_CATEGORY: Record<ToolCategory, Glyph> = {
  read: "read",
  edit: "edit",
  bash: "bash",
  search: "search",
  web: "web",
  agent: "agent",
  todo: "todo",
  mcp: "mcp",
  other: "other",
};

export function glyphFor(kind: EventKind, category?: ToolCategory, isError?: boolean): Glyph {
  if (isError) return "error";
  switch (kind) {
    case "tool_start":
    case "tool_end":
      return BY_CATEGORY[category ?? "other"] ?? "other";
    case "test_fail":
      return "flip";
    case "test_pass":
      return "pass";
    case "waiting":
      return "wait";
    case "session_start":
      return "enter";
    case "subagent_start":
      return "agent";
    case "subagent_end":
    case "session_end":
      return "leave";
    case "error":
      return "error";
    case "thinking":
    case "reply":
      return "think";
    case "prompt":
      return "prompt";
    case "idle":
      return "idle";
    case "flip":
      return "flip";
    case "status":
      return "mood";
    case "shout":
      return "shout";
    case "celebrate":
      return "party";
    default:
      return "other";
  }
}
