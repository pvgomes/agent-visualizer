interface Glyph { w: number; adv: number; ax: number }

export interface BitmapFont {
  readonly cellH: number;
  readonly lineH: number;
  /** Glyph atlas, white on transparent. */
  readonly atlas: Bitmap;
  readonly glyphs: Map<string, Glyph>;
  readonly upper: boolean;
  readonly gap: number;
}

function buildFont(src: [string, string][], rows: number, lineH: number, upper: boolean, gap: number): BitmapFont {
  const maxW = 6;
  const atlas = bitmap(src.length * maxW, rows);
  const glyphs = new Map<string, Glyph>();
  atlas.g.fillStyle = "#fff";
  src.forEach(([ch, data], i) => {
    const r = data.split(" ");
    const w = r[0].length;
    const ax = i * maxW;
    r.forEach((row, y) => {
      for (let x = 0; x < row.length; x++) if (row[x] === "#") atlas.g.fillRect(ax + x, y, 1, 1);
    });
    // Box-drawing glyphs are a full cell wide so they join without gaps.
    glyphs.set(ch, { w, adv: w >= 6 ? w : w + gap, ax });
  });
  return { cellH: rows, lineH, atlas, glyphs, upper, gap };
}

let _font: BitmapFont | null = null;
let _micro: BitmapFont | null = null;
export function FONT(): BitmapFont {
  return (_font ??= buildFont(FONT_SRC, 8, 9, false, 1));
}
export function MICRO(): BitmapFont {
  return (_micro ??= buildFont(MICRO_SRC, 5, 6, true, 1));
}

function glyphOf(f: BitmapFont, ch: string): Glyph {
  const k = f.upper ? ch.toUpperCase() : ch;
  return f.glyphs.get(k) ?? f.glyphs.get("?") ?? f.glyphs.get(" ")!;
}

export function measure(f: BitmapFont, text: string): number {
  let w = 0;
  for (const ch of text) w += glyphOf(f, ch).adv;
  return Math.max(0, w - f.gap);
}

/** Atlas tinted to one colour, cached. */
const tintCache = new Map<string, HTMLCanvasElement>();
function tinted(f: BitmapFont, color: string): HTMLCanvasElement {
  const key = (f === _micro ? "m" : "f") + color;
  let c = tintCache.get(key);
  if (!c) {
    const b = bitmap(f.atlas.w, f.atlas.h);
    b.g.drawImage(f.atlas.c, 0, 0);
    b.g.globalCompositeOperation = "source-in";
    b.g.fillStyle = color;
    b.g.fillRect(0, 0, b.w, b.h);
    c = b.c;
    tintCache.set(key, c);
  }
  return c;
}

/** Draw text at integer scale. Returns the advance width in output pixels. */
export function drawText(
  g: CanvasRenderingContext2D, f: BitmapFont, text: string, x: number, y: number, color: string, scale = 1,
): number {
  const atlas = tinted(f, color);
  let cx = Math.round(x);
  const cy = Math.round(y);
  for (const ch of text) {
    const gl = glyphOf(f, ch);
    if (ch !== " ") g.drawImage(atlas, gl.ax, 0, gl.w, f.cellH, cx, cy, gl.w * scale, f.cellH * scale);
    cx += gl.adv * scale;
  }
  return cx - Math.round(x);
}

/** Text with a 1px drop shadow, the default for in-world signs. */
export function drawTextShadow(
  g: CanvasRenderingContext2D, f: BitmapFont, text: string, x: number, y: number, color: string, shadow: string, scale = 1,
): number {
  drawText(g, f, text, x + scale, y + scale, shadow, scale);
  return drawText(g, f, text, x, y, color, scale);
}

/** Truncate with an ellipsis so the text fits `maxW` font pixels. */
export function fit(f: BitmapFont, text: string, maxW: number): string {
  if (measure(f, text) <= maxW) return text;
  const chars = [...text];
  while (chars.length > 1 && measure(f, chars.join("") + "…") > maxW) chars.pop();
  return chars.join("").trimEnd() + "…";
}

/** A whole string rendered once at 1x, for the label pass to scale up. */
const textCache = new Map<string, Bitmap>();
export function textBitmap(f: BitmapFont, text: string, color: string): Bitmap {
  const key = color + "\u0000" + text;
  let b = textCache.get(key);
  if (!b) {
    if (textCache.size > 600) textCache.clear();
    b = bitmap(Math.max(1, measure(f, text)), f.cellH);
    drawText(b.g, f, text, 0, 0, color, 1);
    textCache.set(key, b);
  }
  return b;
}
